test_that("HotellingModel recomputes equilibria and matches Python", {
  r <- HotellingModel(n_voters = 41, n_candidates = 2, seed = 7)
  s <- sort(.morie_random_uniform(41, seed = 7))
  expect_identical(r$equilibrium_positions, c(s[21], s[21]))
  expect_equal(r$max_gain, 0)
  expect_false(HotellingModel(n_candidates = 3)$has_pure_equilibrium)
  expect_null(HotellingModel(n_candidates = 3)$equilibrium_positions)
  r4 <- HotellingModel(n_voters = 60, n_candidates = 4, seed = 3)
  s <- sort(.morie_random_uniform(60, seed = 3))
  q <- stats::quantile(s, c(0.25, 0.25, 0.75, 0.75), names = FALSE)
  expect_equal(r4$equilibrium_positions, q, tolerance = 1e-15)
  expect_equal(r4$max_gain, max(PluralityCompetition(s, q)$gain), tolerance = 1e-15)
  expect_equal(HotellingModel(n_voters = 3, n_candidates = 7)$fractions, c(1, 1, 3, 5, 7, 9, 9) / 10)
  # Python arm, n_candidates = 5, seed 42 (15 significant digits)
  r5 <- HotellingModel(n_candidates = 5)
  expect_equal(r5$equilibrium_positions[c(1, 3, 4)], c(0.221964949509129, 0.439469357253984, 0.799725755932741),
               tolerance = 1e-14)
  expect_equal(r5$max_gain, 0.11, tolerance = 1e-12)
})
