test_that("marine formulas recomputed", {
  x <- log10(0.006 / 0.004)
  a <- c(0.2424, -2.7423, 1.8017, 0.0015, -1.2280)
  expect_equal(OceanChlorophyll(matrix(c(0.005, 0.006), 1), 0.004, "OC3M"), 10^sum(a * x^(0:4)), tolerance = 1e-13)
  expect_equal(EuphoticDepth(0.2), log(100) / 0.2, tolerance = 1e-15)
  expect_equal(PracticalSalinity(42.914, 15 / 1.00024), 35, tolerance = 1e-7)
  r <- SedimentTransport(2, 0.001)
  expect_equal(r$theta, 2 / (1625 * 9.81 * 0.001), tolerance = 1e-14)
  expect_equal(Co2Flux(10, 25, 35, 400, 400)$flux, 0)
  zs <- c(2, 5, 9, 14)
  li <- 0.01 + 0.3 * exp(-0.16 * zs)
  lj <- 0.005 + 0.2 * exp(-0.24 * zs)
  d <- DepthInvariantIndex(li, lj, 0.01, 0.005, li, lj)
  expect_equal(d$ratio, 2 / 3, tolerance = 1e-12)
  expect_lt(diff(range(d$dii)), 1e-12)
  expect_equal(BareSoilIndex(0.1, 0.2, 0.3, 0.4), 0.2, tolerance = 1e-14)
  ys <- seq(-1500, 1500, by = 0.5)
  cc <- PlumeConcentration(rep(1500, length(ys)), ys, 2, 0.25, 6, 1.5, 2e-5)
  expect_equal(6 * 0.25 * 0.5 * (sum(cc) - 0.5 * (cc[1] + cc[length(cc)])), 2 * exp(-2e-5 * 1500 / 0.25), tolerance = 1e-9)
  o <- OilSpillDrift(0, 0, c(0.1, -0.2), c(5, 10), 6, 1, 3, diffusivity = 0)
  expect_equal(o$centroid, c(0.25, 0.1) * 6 * 3600, tolerance = 1e-12)
})
