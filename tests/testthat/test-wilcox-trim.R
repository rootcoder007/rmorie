test_that("trimmed-mean inference matches WRS2 and the formulas", {
  x <- c(2.1, 3.4, 1.9, 5.6, 4.4, 3.3, 2.8, 6.1, 3.9, 4.2, 2.2, 5.0, 40)
  y <- c(3.3, 4.1, 2.7, 6.8, 5.9, 4.4, 3.6, 7.2, 4.8, 5.3, 3.1, 6.6, 4.0, 9.5, 5.5)
  expect_equal(TrimSE(x)$se, 0.607161042974655, tolerance = 1e-12)
  t <- TrimCI(x, null_value = 3)
  expect_equal(c(t$statistic, t$df), c(1.42740822504128, 8), tolerance = 1e-11)
  r <- Yuen(x, y)
  expect_equal(c(abs(r$statistic), r$df, r$p_value), c(1.3652186507445, 15.9951439167129, 0.191079509438389), tolerance = 1e-9)
  expect_equal(AkpD(x, null_value = 3)$d, 0.423564527123191, tolerance = 1e-12)
  expect_equal(R2FTest(0.3, 40, 3)$statistic, 36 / 3 * 0.3 / 0.7, tolerance = 1e-12)
  fit <- fitted(lm(c(1.2, 1.9, 3.4, 3.8, 5.3, 5.9) ~ I(1:6)))
  expect_equal(ExplPow(c(1.2, 1.9, 3.4, 3.8, 5.3, 5.9), fit)$eta2,
               summary(lm(c(1.2, 1.9, 3.4, 3.8, 5.3, 5.9) ~ I(1:6)))$r.squared, tolerance = 1e-12)
  o <- CiOvlap(x[1:12], y)
  expect_true(o$welch_ratio >= o$ratio)
  skip_if_not_installed("WRS2")
  expect_equal(TrimSE(x, 0.1)$se, WRS2::trimse(x, 0.1), tolerance = 1e-12)
  expect_equal(.wil_winvar(y, 0.1), WRS2::winvar(y, 0.1), tolerance = 1e-12)
})
