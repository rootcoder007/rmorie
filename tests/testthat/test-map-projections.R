test_that("UTM, geodesics and local tangent planes equal PROJ and geosphere", {
  P <- rbind(c(10, 50), c(-73.5, 40.7), c(151.2, -33.9), c(2.3, 48.8), c(-120, 65), c(30, -60), c(0.5, 0.2),
      c(170, 10))
  u <- t(apply(P[c(1, 2, 4), ], 1, function(q) MapProject(q[1], q[2], "utm", zone = 33)))
  expect_equal(u, rbind(c(141743.6322386554, 5550619.375419196), c(-5822280.734461887, 9804218.439038634),
      c(-431562.91082995094, 5483506.3678281335)), tolerance = 1e-12)
  expect_equal(c(UtmZone(10, 50), UtmZone(5, 60), UtmZone(10, 75), UtmZone(-180, 0)), c(32, 32, 33, 1))
  v <- sapply(1:7, function(i) unlist(VincentyInverse(P[i, 1], P[i, 2], P[i + 1, 1], P[i + 1, 2])[1:2]))
  expect_equal(v[1, ], c(6278307.030294688, 16032798.727959488, 16965121.49750116, 6445790.919946417,
      18385068.557411436, 7145640.221946153, 18400542.21861004), tolerance = 1e-9)
  expect_equal(v[2, ], c(295.1688375814649, 266.4851845926949, 312.4312336063054, 335.0119062966755,
      83.71287715948918, 326.81896041989086, 44.418887408154795), tolerance = 1e-9)
  expect_equal(sapply(1:7, function(i) GreatCircleDistance(P[i, 1], P[i, 2], P[i + 1, 1], P[i + 1, 2])),
               c(6268375.533418535, 16051388.894530298, 16987063.05388962, 6432055.517463724,
                   18416689.715638246, 7168505.200412988, 18412138.547421243), tolerance = 1e-12)
  e <- GeodeticToEnu(10.02, 50.01, 350, 10, 50, 300)
  expect_equal(e$ecef, c(4044589.5304249157, 714626.0732880278, 4863772.08542388), tolerance = 1e-12)
  expect_equal(GeodeticToEnu(10, 50, 350, 10, 50, 300)$enu, c(0, 0, 50), tolerance = 1e-10)
  expect_error(MapProject(0, 0, "robin"), "unknown")
})
