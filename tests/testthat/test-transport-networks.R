test_that("paths, tours and routing", {
  E <- rbind(c(1, 2, 4), c(1, 3, 1), c(3, 2, 2), c(2, 4, 1), c(3, 4, 5), c(4, 5, 3), c(2, 5, 6), c(3, 5, 9))
  r <- ShortestPath(5, E, 1, 5)
  expect_equal(r$distance, c(0, 3, 1, 4, 7))
  expect_equal(r$path, c(1, 3, 2, 4, 5))
  k <- KShortestPaths(4, rbind(c(1, 2, 1), c(2, 4, 1), c(1, 3, 1.5), c(3, 4, 1), c(2, 3, 0.2)), 1, 4, 3)
  expect_equal(k$costs, c(2, 2.2, 2.5))
  expect_equal(k$paths[[2]], c(1, 2, 3, 4))
  t <- TspTour(rbind(c(0, 2, 9, 10), c(1, 0, 6, 4), c(15, 7, 0, 8), c(6, 3, 12, 0)))
  expect_equal(t$tour, c(1, 3, 4, 2))
  expect_equal(t$length, 21)
  D <- rbind(c(0, 4, 4, 5, 5), c(4, 0, 1, 7, 8), c(4, 1, 0, 7, 7), c(5, 7, 7, 0, 1), c(5, 8, 7, 1, 0))
  cw <- ClarkeWrightVrp(D, c(0, 1, 1, 1, 1), 2)
  expect_equal(cw$routes, list(c(2, 3), c(4, 5)))
  expect_equal(cw$cost, 20)
  expect_error(ShortestPath(2, rbind(c(1, 2, -1)), 1), "nonnegative")
})

test_that("distribution, choice, assignment, signals", {
  g <- GravityDistribution(c(100, 50), c(60, 90), rbind(c(1, 2), c(2, 1)), 0.5)
  expect_equal(round(g$trips, 4), rbind(c(47.51, 52.49), c(12.49, 37.51)))
  expect_equal(LogitModeShares(rbind(c(0, log(3))))$shares[1, ], c(0.25, 0.75))
  ta <- TrafficAssignment(2, rbind(c(1, 2, 10, 100), c(1, 2, 15, 100)), rbind(c(1, 2, 200)), alpha = 1, beta = 1)
  expect_equal(ta$flow, c(140, 60), tolerance = 1e-8)
  w <- WebsterSignal(c(0.25, 0.15), c(0.5, 0.5), 10)
  expect_equal(c(w$cycle, w$green), c(100, 56.25, 33.75))
  expect_error(WebsterSignal(c(0.3, 0.3), c(0.5, 0.5), 10), "below 1")
})
