test_that("Twostage is Cochran's two-stage ratio estimator", {
  Y <- list(c(3, 5, 4), c(8, 6, 7, 9), c(2, 1, 3))
  Nl <- c(10, 12, 8)
  M <- 20
  N <- 220
  r <- Twostage(Y, Nl, M, N)
  yb <- vapply(Y, mean, 0)
  s2 <- vapply(Y, var, 0)
  nl <- lengths(Y)
  est <- sum(Nl * yb) / sum(Nl)
  bt <- (1 - 3 / M) * sum((Nl * yb - Nl * est)^2) / (3 * 2)
  wt <- sum(Nl^2 * (1 - nl / Nl) * s2 / nl) / (3 * M)
  v <- (M / N)^2 * (bt + wt)
  expect_equal(r$estimate, est, tolerance = 1e-12)
  expect_equal(r$se, sqrt(v), tolerance = 1e-12)
  expect_equal(c(r$ci_lower, r$ci_upper), est + c(-1, 1) * qnorm(0.975) * sqrt(v), tolerance = 1e-12)
  expect_equal(r$between_term + r$within_term, v, tolerance = 1e-12)
  expect_error(Twostage(Y[1], Nl[1], M, N), "at least two PSUs")
  expect_error(Twostage(Y, Nl[-1], M, N), "one entry per sampled PSU")
  expect_error(Twostage(Y, Nl, 2, N), "M must be at least")
  expect_error(Twostage(list(1, 2:3), c(5, 5), M, N), "at least two elements")
  expect_error(Twostage(Y, c(2, 12, 8), M, N), "cannot exceed its population")
})

test_that("MultM matches the lm mediator and outcome regressions", {
  set.seed(2)
  n <- 30
  x <- rnorm(n)
  cv <- rnorm(n)
  m1 <- 0.5 * x + 0.2 * cv + rnorm(n)
  m2 <- -0.3 * x + rnorm(n)
  y <- 0.4 * x + 0.7 * m1 - 0.2 * m2 + 0.1 * cv + rnorm(n)
  r <- MultM(y, x, rbind(m1, m2), C = cv)
  a <- c(coef(lm(m1 ~ x + cv))[["x"]], coef(lm(m2 ~ x + cv))[["x"]])
  fy <- coef(lm(y ~ x + m1 + m2 + cv))
  expect_equal(r$a, a, tolerance = 1e-10)
  expect_equal(r$b, unname(fy[c("m1", "m2")]), tolerance = 1e-10)
  expect_equal(r$direct, fy[["x"]], tolerance = 1e-10)
  expect_equal(r$indirect_total, sum(a * fy[c("m1", "m2")]), tolerance = 1e-10)
  expect_equal(r$total, r$direct + r$indirect_total, tolerance = 1e-12)
  r0 <- MultM(y, x, cbind(m1, m2))
  expect_equal(r0$a[1], coef(lm(m1 ~ x))[["x"]], tolerance = 1e-10)
  expect_error(MultM(y[1:5], x[1:5], cbind(m1, m2)[1:5, ]), "too few observations")
  expect_error(MultM(y, x[-1], cbind(m1, m2)), "share their first dimension")
  expect_error(MultM(y, x, cbind(m1, m2), C = cv[-1]), "wrong number of rows")
})

test_that("Mutinfo is the plug-in mutual information with Miller-Madow", {
  a <- c("u", "u", "v", "w", "v", "u", "w", "w", "v", "u")
  b <- c(1, 2, 1, 2, 2, 1, 1, 2, 1, 1)
  P <- table(a, b) / 10
  px <- rowSums(P)
  py <- colSums(P)
  nz <- P > 0
  mi <- sum(P[nz] * log(P[nz] / outer(px, py)[nz]))
  r <- Mutinfo(a, b)
  expect_equal(r$mi, mi, tolerance = 1e-12)
  expect_equal(r$bits, mi / log(2), tolerance = 1e-12)
  expect_equal(r$hx, -sum(px * log(px)), tolerance = 1e-12)
  expect_equal(r$hxy, -sum(P[nz] * log(P[nz])), tolerance = 1e-12)
  expect_equal(r$mi, r$hx + r$hy - r$hxy, tolerance = 1e-12)
  expect_equal(r$mm, mi - (sum(nz) - 3 - 2 + 1) / 20, tolerance = 1e-12)
  expect_equal(Mutinfo(NULL, a, b)$mi, mi, tolerance = 1e-12)
  expect_true(is.nan(Mutinfo(character(0), character(0))$mm))
})

