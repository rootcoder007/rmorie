# Coverage for the Msm* equation wrappers of Montesinos Lopez et al.
# (2022): one-way models, classification metrics, Brier score, linear
# mixed models and their likelihoods, multi-trait BLUP, Bayesian and OLS
# regression, ordinal designs, penalised multinomial likelihoods, RKHS
# risks and fits, ANN loss, basis expansion, ZAP pieces and the expected
# prediction error. Every numbered alias is checked against its base.

groups <- list(c(4.1, 5.2, 4.8, 5.0), c(6.3, 5.9, 6.8, 6.1), c(3.9, 4.4, 4.0, 4.6))
same_as <- function(base, aliases, ...) {
  ref <- do.call(base, list(...))
  for (nm in aliases) expect_equal(do.call(get(nm), list(...)), ref, info = nm)
}

test_that("the one-way model family", {
  y <- unlist(groups)
  g <- factor(rep(1:3, each = 4))
  a <- anova(lm(y ~ g))
  r1 <- Msm001(c(1, 2, 3), function(v) v^2, noise = c(0.1, -0.2, 0.3))
  expect_equal(r1$y, c(1.1, 3.8, 9.3), tolerance = 1e-12)
  expect_equal(r1$mean_error, 0.2 / 3, tolerance = 1e-12)
  expect_equal(Msm001(c(2, 5))$y, c(2, 5))
  m2 <- Msm002(groups)
  expect_equal(c(m2$beta, m2$sd_residual), c(mean(y), sd(y)), tolerance = 1e-12)
  same_as("Msm002", c("Msm083", "Msm084", "Msm159", "Msm160", "Msm315", "Msm316", "Msm317", "Msm318",
                      "Msm319", "Msm320", "Msm321", "Msm322"), groups)
  m3 <- Msm003(groups)
  expect_equal(m3$beta, as.numeric(tapply(y, g, mean)), tolerance = 1e-12)
  expect_equal(m3$sd_residual, sqrt(a["Residuals", "Mean Sq"]), tolerance = 1e-12)
  same_as("Msm003", c("Msm004", "Msm236", "Msm237", "Msm238", "Msm239"), groups)
  m5 <- Msm005(groups)
  expect_equal(m5$deviations, as.numeric(tapply(y, g, mean)) - mean(y), tolerance = 1e-12)
  expect_equal(m5$deviations_sum, 0, tolerance = 1e-12)
  m6 <- Msm006(groups)
  s2b <- max((a["g", "Mean Sq"] - a["Residuals", "Mean Sq"]) / 4, 0)
  expect_equal(m6$sigma2_b, s2b, tolerance = 1e-12)
  expect_equal(m6$icc, s2b / (s2b + a["Residuals", "Mean Sq"]), tolerance = 1e-12)
  expect_error(Msm002(list(1:3, 1:2)), "balanced")
})

test_that("classification metrics and the Brier score", {
  yt <- c(0, 1, 2, 1, 0, 2, 2, 1)
  yp <- c(0, 2, 2, 1, 1, 2, 0, 1)
  C <- table(factor(yt, 0:2), factor(yp, 0:2))
  ttp <- sum(diag(C))
  p7 <- Msm007(yt, yp, class_index = 2)
  expect_equal(p7$estimate, ttp / (ttp + sum(C[-3, 3])), tolerance = 1e-12)
  expect_equal(p7$pCCC, ttp / 8, tolerance = 1e-12)
  s8 <- Msm008(yt, yp, class_index = 1)
  expect_equal(s8$sensitivity, ttp / (ttp + sum(C[2, -2])), tolerance = 1e-12)
  expect_equal(s8$specificity, sum(C[-2, -2]) / (sum(C[-2, -2]) + sum(C[-2, 2])), tolerance = 1e-12)
  P <- rbind(c(0.7, 0.2, 0.1), c(0.1, 0.6, 0.3), c(0.2, 0.2, 0.6), c(0.3, 0.4, 0.3))
  y <- c(0, 1, 2, 0)
  b <- Msm009(P, y)
  oh <- outer(y, 0:2, "==") * 1
  expect_equal(b$brier, mean(rowSums((P - oh)^2)), tolerance = 1e-12)
  expect_equal(Msm009(P, y, halved = TRUE)$brier, mean(rowSums((P - oh)^2)) / 2, tolerance = 1e-12)
  expect_equal(b$mean_log_loss, -mean(log(P[cbind(1:4, y + 1)])), tolerance = 1e-12)
})

test_that("the linear mixed model wrappers", {
  set.seed(1)
  n <- 10
  X <- cbind(1, rnorm(n))
  Z <- outer(rep(1:3, length.out = n), 1:3, "==") * 1
  D <- diag(c(0.5, 0.8, 0.3))
  y <- as.numeric(X %*% c(1, 0.5) + Z %*% c(0.3, -0.4, 0.2) + rnorm(n))
  V <- Z %*% D %*% t(Z) + diag(n)
  Vi <- solve(V)
  bh <- solve(t(X) %*% Vi %*% X, t(X) %*% Vi %*% y)
  u <- D %*% t(Z) %*% Vi %*% (y - X %*% bh)
  r <- Msm010(X, Z, y, D)
  expect_equal(r$beta, as.numeric(bh), tolerance = 1e-9)
  expect_equal(r$blup, as.numeric(u), tolerance = 1e-9)
  ll <- -0.5 * (n * log(2 * pi) + as.numeric(determinant(V)$modulus) + sum((y - X %*% bh) * (Vi %*% (y - X %*% bh))))
  expect_equal(r$loglik, ll, tolerance = 1e-9)
  same_as("Msm010", c("Msm013", "Msm014", "Msm019", "Msm027"), X, Z, y, D)
  re <- Msm011(X, Z, y, D, restricted = TRUE)
  expect_equal(re$loglik, ll + 0.5 * n * log(2 * pi) - 0.5 * as.numeric(determinant(t(X) %*% Vi %*% X)$modulus),
               tolerance = 1e-9)
  expect_equal(Msm011(X, Z, y, D, beta = c(1, 0.5))$loglik,
               -0.5 * (n * log(2 * pi) + as.numeric(determinant(V)$modulus) + sum((y - X %*% c(1, 0.5)) * (Vi %*% (y - X %*% c(1, 0.5))))),
               tolerance = 1e-9)
  same_as("Msm011", "Msm012", X, Z, y, D)
})

test_that("the multi-trait genomic BLUP equals GLS on the Kronecker system", {
  Y <- rbind(c(1.2, 3.1), c(0.8, 2.5), c(1.5, 3.3), c(1.1, 2.9))
  G <- matrix(c(1, 0.3, 0.1, 0, 0.3, 1, 0.2, 0.1, 0.1, 0.2, 1, 0.3, 0, 0.1, 0.3, 1), 4)
  St <- matrix(c(0.5, 0.2, 0.2, 0.4), 2)
  Rt <- diag(c(0.3, 0.2))
  r <- Msm026(Y, diag(4), G, St, Rt)
  y <- as.numeric(t(Y))
  Xk <- kronecker(matrix(1, 4, 1), diag(2))
  Zk <- kronecker(diag(4), diag(2))
  V <- Zk %*% kronecker(G, St) %*% t(Zk) + kronecker(diag(4), Rt)
  Vi <- solve(V)
  mu <- solve(t(Xk) %*% Vi %*% Xk, t(Xk) %*% Vi %*% y)
  b <- kronecker(G, St) %*% t(Zk) %*% Vi %*% (y - Xk %*% mu)
  expect_equal(r$mu, as.numeric(mu), tolerance = 1e-9)
  expect_equal(r$b, as.numeric(b), tolerance = 1e-9)
  same_as("Msm026", c("Msm029", "Msm030", "Msm031"), Y, diag(4), G, St, Rt)
  x <- matrix(c(0.1, -0.2, 0.3, 0.05, 0.2, 0.1, -0.1, 0.4), 8)
  r28 <- Msm028(Y, diag(4), G, St, Rt, X = x)
  X2 <- cbind(Xk, x)
  be <- solve(t(X2) %*% Vi %*% X2, t(X2) %*% Vi %*% y)
  expect_equal(r28$beta, as.numeric(be), tolerance = 1e-9)
})

test_that("Bayesian and OLS regression, the flat prior and the expected prediction error", {
  set.seed(2)
  X <- matrix(rnorm(24), 12)
  y <- as.numeric(1 + X %*% c(2, -1) + rnorm(12))
  f <- lm(y ~ X)
  r <- Msm042(X, y)
  s2 <- summary(f)$sigma^2
  expect_equal(r$posterior_mean_beta, unname(coef(f)), tolerance = 1e-9)
  expect_equal(r$posterior_sd_beta, unname(summary(f)$coefficients[, 2]), tolerance = 1e-9)
  expect_equal(r$posterior_mean_sigma2, (9 * s2 / 2) / (9 / 2 - 1), tolerance = 1e-9)
  same_as("Msm042", c("Msm044", "Msm045", "Msm057", "Msm058", "Msm059", "Msm060"), X, y)
  o <- Msm332(X, y)
  expect_equal(o$residuals, unname(residuals(f)), tolerance = 1e-9)
  same_as("Msm332", "Msm333", X, y)
  p <- Msm043(2.5)
  expect_equal(c(p$density, p$log_density), c(0.4, -log(2.5)), tolerance = 1e-12)
  same_as("Msm043", c("Msm047", "Msm077"), 2.5)
  expect_error(Msm043(0), "positive")
  e <- Msm334(1.5, c(0.5, -1), c(2, 4))
  expect_equal(e$estimate, 1.5 * (1 + 0.25 / 2 + 1 / 4), tolerance = 1e-12)
  expect_error(Msm334(1, 1, 0), "positive")
})

test_that("ordinal designs and penalised multinomial likelihoods", {
  XE <- matrix(c(1, 0, 1, 0, 1, 0), 3)
  XM <- matrix(1:6, 3)
  r <- Msm092(3, X_E = XE, X = XM)
  expect_equal(r$design, cbind(XE, XM))
  expect_equal(unlist(r$widths), c(environments = 2L, markers = 2L))
  same_as("Msm092", c("Msm093", "Msm097", "Msm099", "Msm103"), 3, XE, XM)
  ZL <- diag(3)
  Lg <- matrix(c(1, 0.5, 0.2, 0, 1, 0.3, 0, 0, 1), 3)
  r98 <- Msm098(3, XE, ZL, Lg)
  expect_equal(r98$design, cbind(XE, ZL %*% Lg))
  same_as("Msm098", c("Msm101", "Msm102"), 3, XE, ZL, Lg)
  expect_error(Msm092(3), "at least one block")
  X <- cbind(c(0.2, -1, 0.5, 1.4), c(1, 0, 1, 1))
  y <- c(0, 2, 1, 0)
  b0 <- c(0.1, -0.2)
  B <- matrix(c(0.5, -0.3, 0.2, 0.8), 2)
  eta <- cbind(sweep(X %*% t(B), 2, b0, "+"), 0)
  P <- exp(eta) / rowSums(exp(eta))
  ll <- sum(log(P[cbind(1:4, y + 1)]))
  r9 <- Msm109(X, y, b0, B, lam = 0.3)
  expect_equal(c(r9$loglik, r9$estimate), c(ll, ll - 0.3 * sum(B^2)), tolerance = 1e-12)
  same_as("Msm109", c("Msm111", "Msm114", "Msm117", "Msm118"), X, y, b0, B, 0.3)
  r15 <- Msm115(X, y, b0, B, lam = 0.3)
  expect_equal(r15$estimate, ll - 0.3 * sum(abs(B)), tolerance = 1e-12)
  same_as("Msm115", "Msm119", X, y, b0, B, 0.3)
})

test_that("RKHS risks and the squared-loss RKHS fit", {
  x <- c(0.1, 0.4, 0.5, 0.9, 1.3)
  K <- exp(-outer(x, x, "-")^2)
  y <- c(0.3, 0.9, 1.1, 0.8, 0.2)
  beta <- c(0.1, -0.2, 0.3, 0.05, 0.1)
  f <- 0.2 + as.numeric(K %*% beta)
  nrm <- sum(beta * (K %*% beta))
  r <- Msm123(K, y, beta, eta0 = 0.2, lam = 0.5)
  expect_equal(r$objective, mean((y - f)^2) + 0.5 * nrm, tolerance = 1e-12)
  yb <- c(1, 0, 1, 1, 0)
  expect_equal(Msm123(K, yb, beta, 0.2, 0.5, "logistic")$empirical_risk, mean(log1p(exp(-(2 * yb - 1) * f))), tolerance = 1e-12)
  expect_equal(Msm123(K, yb, beta, 0.2, 0.5, "hinge")$empirical_risk, mean(pmax(0, 1 - (2 * yb - 1) * f)), tolerance = 1e-12)
  same_as("Msm123", c("Msm124", "Msm127"), K, y, beta, 0.2, 0.5)
  expect_error(Msm123(K, y, beta, loss = "huber"), "unknown loss")
  s <- Msm128(K, y, lam = 0.2)
  res <- y - s$fitted
  expect_lt(abs(mean(res)), 1e-9)
  expect_lt(max(abs(-2 / 5 * t(K) %*% res + 0.2 * K %*% s$beta)), 1e-8)
  expect_equal(s$objective, mean(res^2) + 0.1 * sum(s$beta * (K %*% s$beta)), tolerance = 1e-12)
  same_as("Msm128", c("Msm129", "Msm130", "Msm133", "Msm134"), K, y, 0.2)
})

test_that("ANN loss, basis expansion and the ZAP pieces", {
  expect_equal(Msm249(matrix(c(1, 2, 3, 4), 2), matrix(c(1, 1, 2, 4), 2))$sse, 0.5 * 2, tolerance = 1e-12)
  t <- c(0, 0.2, 0.35, 0.5)
  b <- c(1, 0.5, -0.3)
  e <- Msm262(t, b, period = 2)
  expect_equal(e$beta_t, 1 + 0.5 * sin(2 * pi * t / 2) - 0.3 * cos(2 * pi * t / 2), tolerance = 1e-12)
  u <- Msm262(t, b)
  expect_equal(u$beta_t, 1 + 0.5 * sin(2 * pi * t / 0.5) - 0.3 * cos(2 * pi * t / 0.5), tolerance = 1e-12)
  z <- Msm323(0.4, -1)
  expect_equal(c(z$mu, z$theta), c(exp(0.4), plogis(-1)), tolerance = 1e-12)
  same_as("Msm323", "Msm324", 0.4, -1)
  yp <- c(1, 2, 1, 3, 5, 2)
  zt <- Msm325(yp)
  mu <- uniroot(function(m) m / (1 - exp(-m)) - mean(yp), c(1e-6, 20), tol = 1e-14)$root
  expect_equal(zt$mu, mu, tolerance = 1e-9)
  ll <- function(v, m) sum(dpois(v, m, log = TRUE)) - length(v) * log(1 - exp(-m))
  expect_equal(zt$loglik, ll(yp, zt$mu), tolerance = 1e-12)
  sp <- Msm325(yp, x = c(1, 2, 3, 4, 5, 6))$split
  cand <- 1:5
  lls <- vapply(cand, function(v) {
    L <- yp[1:6 <= v]
    R <- yp[1:6 > v]
    ml <- function(w) if (mean(w) <= 1) 0 else uniroot(function(m) m / (1 - exp(-m)) - mean(w), c(1e-6, 50), tol = 1e-14)$root
    lf <- function(w) if (ml(w) == 0) -Inf else ll(w, ml(w))
    lf(L) + lf(R)
  }, 0)
  expect_equal(sp$threshold, cand[which.max(lls)])
  same_as("Msm325", "Msm326", yp)
  expect_equal(Msm327(0.3, 2)$y_hat, 0.7 * 2 / (1 - exp(-2)), tolerance = 1e-12)
  same_as("Msm327", "Msm328", 0.3, 2)
  expect_equal(Msm329(0.6, 2.5)$y_hat, 0)
  expect_equal(Msm329(0.4, 2.5)$y_hat, 2.5)
  same_as("Msm329", c("Msm330", "Msm331"), 0.4, 2.5)
})
