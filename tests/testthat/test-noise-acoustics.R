test_that("level statistics and day-evening-night indicators", {
  s <- LevelStatistics(c(50, 52, 55, 60, 71))
  expect_equal(unlist(s[c("L10", "L50", "L90", "Lmax")]), c(L10 = 66.6, L50 = 55, L90 = 50.8, Lmax = 71))
  hourly <- c(rep(45, 7), rep(65, 12), rep(60, 4), 45)
  r <- DayEveningNight(hourly)
  expect_equal(c(r$Lday, r$Levening, r$Lnight), c(65, 60, 45))
  expect_equal(r$Lden, 10 * log10((16 * 10^6.5 + 8 * 10^5.5) / 24))
  expect_equal(r$CNEL, 10 * log10((12 * 10^6.5 + 9 * 10^6 + 10 * (10^6 + 8 * 10^4.5)) / 24))
  expect_equal(round(AircraftDnl(rep(90, 10), 90), 6), 53.645163)
  expect_equal(SoundExposureLevel(rep(80, 10)), 90)
  expect_error(DayEveningNight(rep(60, 23)), "24")
})

test_that("ISO 9613 propagation terms", {
  f <- 1000 * 10^(0.3 * (-4:3))
  expect_lte(max(abs(1000 * AtmosphericAbsorption(f) - c(0.1, 0.3, 1.1, 2.8, 5.0, 9.0, 22.9, 76.6))), 0.05)
  d <- AttenuationDistance(100, 40, alpha = 0.01)
  expect_equal(PointSourceLevel(100, d, alpha = 0.01), 40, tolerance = 1e-9)
  expect_equal(round(unlist(GroundAttenuation(200, 2, 2)), 6), c(A_gr = 4.43, D_omega = 3.009432))
  expect_equal(round(BarrierAttenuation(10, 10, 19, 1000)$Dz, 5), 17.84788)
  expect_equal(BarrierAttenuation(100, 100, 150, 8000)$Dz, 20)
  expect_equal(c(FoliageAttenuation(15, 4000), FoliageAttenuation(50, 1000), FoliageAttenuation(300, 8000)), c(2, 3, 24))
  expect_equal(round(NoiseMap(c(100, 100), rbind(c(0, 0), c(20, 0)), rbind(c(10, 0))), 4), 72.0103)
  z <- NoiseZones(c(50, 57, 66, 80), population = c(10, 20, 30, 40))
  expect_equal(z$zone, c(0, 1, 3, 5))
  expect_equal(z$counts, c(10, 20, 0, 30, 0, 40))
})

test_that("road, construction, vibration, underwater and dose-response", {
  expect_equal(round(CrtnRoadNoise(1000)$L10, 6), 72.198781)
  expect_equal(round(ConstructionNoise(85, 100, 40)$Leq, 6), 75)
  expect_equal(VibrationPropagation(94, 250), 64)
  expect_equal(VibrationPropagation(0.2, 100, kind = "ppv"), 0.025)
  expect_equal(round(UnderwaterPropagation(200, 1000, 10)$RL, 5), 138.81297)
  expect_equal(round(NoiseAnnoyance(c(42, 60), "road"), 6), c(0, 10.314778))
  h <- NoiseHealthRisk(c(50, 63), population = c(1, 1))
  expect_equal(h$rr, c(1, 1.08))
  expect_equal(round(h$paf, 6), 0.038462)
})
