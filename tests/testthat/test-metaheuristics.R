rb3 <- function(x) (1 - x[1])^2 + 100 * (x[2] - x[1]^2)^2 + (x[3] - 0.5)^2
sphere <- function(x) sum(x^2)
algs <- list(artificial_bee_colony = ArtificialBeeColony, ant_colony_continuous = AntColonyContinuous, bat_algorithm = BatAlgorithm, cuckoo_search = CuckooSearch, firefly_algorithm = FireflyAlgorithm, grey_wolf_optimizer = GreyWolfOptimizer, harris_hawks_optimizer = HarrisHawksOptimizer, jaya_algorithm = JayaAlgorithm, moth_flame_optimizer = MothFlameOptimizer, sine_cosine_algorithm = SineCosineAlgorithm, teaching_learning_optimizer = TeachingLearningOptimizer, whale_optimization = WhaleOptimization)

test_that("metaheuristics keep a monotone best-so-far inside the box", {
  bounds <- list(c(-5, 5), c(-4, 6), c(-3, 3))
  for (nm in names(algs)) {
    r <- algs[[nm]](sphere, bounds, n_pop = 10, max_iter = 30, seed = 3)
    expect_true(all(diff(r$history) <= 0), label = nm)
    expect_equal(r$fun, sphere(r$x), label = nm)
    expect_true(all(r$x >= c(-5, -4, -3) & r$x <= c(5, 6, 3)), label = nm)
    expect_identical(r$history, algs[[nm]](sphere, bounds, n_pop = 10, max_iter = 30, seed = 3)$history)
  }
})

test_that("metaheuristic runs match the Python arm", {
  r <- ArtificialBeeColony(rb3, list(c(-2, 2), c(-2, 2), c(-1, 3)), n_pop = 12, max_iter = 40, seed = 7)
