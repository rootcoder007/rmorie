test_that("spatial Monte Carlo", {
  r <- McIntegrate(function(x, y) x * y, bounds = rbind(c(0, 2), c(1, 3)), n = 500, seed = 3)
  u <- .morie_random_uniform(1000, seed = 3, stream = 0)
  v <- (2 * u[seq(1, 999, 2)]) * (1 + 2 * u[seq(2, 1000, 2)])
  expect_equal(r$mean, mean(v))
  lin <- McIntegrate(function(x) 3 * x + 1, bounds = rbind(c(0, 1)), n = 100, method = "antithetic")
  expect_equal(c(lin$mean, lin$se_mean), c(2.5, 0))
  sq <- list(rbind(c(0, 0), c(0.5, 0), c(0.5, 1), c(0, 1)), rbind(c(0.5, 0), c(1, 0), c(1, 1), c(0.5, 1)))
  s <- McStratified(function(x, y) if (x < 0.5) 1 else 3, sq, n = 100)
  expect_equal(c(s$mean, s$se), c(2, 0))
  cv <- McControlVariate(c(1, 2, 3, 4), c(0.9, 2.1, 2.9, 4.1), 2.5)
  expect_equal(cv$estimate, 2.5)
  expect_equal(McConvergence(c(1, 3, 2, 4), batches = 2)$running_mean, c(1, 2, 2, 2.5))
})
