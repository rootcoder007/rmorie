test_that("association measures follow their definitions", {
  x <- c("theft", "assault", "theft", "fraud", "theft", "assault", "fraud", "fraud", "fraud")
  expect_equal(VariationRatio(x), 1 - 4 / 9, tolerance = 1e-15)
  tb <- matrix(c(23, 11, 7, 19), 2)
  r <- YuleAssociation(tb)
  expect_equal(r$Q, (23 * 19 - 7 * 11) / (23 * 19 + 7 * 11), tolerance = 1e-14)
  expect_equal(r$Q, 2 * r$Y / (1 + r$Y^2), tolerance = 1e-13)
  tt <- TostCorrelation(0.08, 120, -0.25, 0.3)
  zl <- (atanh(0.08) - atanh(-0.25)) * sqrt(117)
  zh <- (atanh(0.08) - atanh(0.3)) * sqrt(117)
  expect_equal(tt$p_value, max(1 - stats::pnorm(zl), stats::pnorm(zh)), tolerance = 1e-10)
  S <- matrix(c(2, 0.3, 0.1, 0.3, 1, 0.2, 0.1, 0.2, 1.5), 3)
  A <- rbind(c(1, -1, 0), c(0.5, 0.5, 2))
  a <- AffineMoments(c(1, -2, 0.5), S, A, c(1, 2))
  expect_equal(a$mean, c(4, 2.5), tolerance = 1e-14)
  expect_equal(a$cov, A %*% S %*% t(A), tolerance = 1e-14)
  expect_error(VariationRatio(character(0)), "empty")
})
