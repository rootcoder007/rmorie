test_that("two-regressor attenuation: the coefficients solve the normal equations and the bias has the sign of beta1 s12", {
  m <- list(s11 = 1, s22 = 2, s12 = 0.6, su2 = 0.5)
  r <- morie_attenuation_two_regressor(beta1 = 1.5, beta2 = -0.5, s11 = 1, s22 = 2, s12 = 0.6, su2 = 0.5)
  expect_equal(attr(r, "theorem"), "Research.P5.Attenuation.two_regressor_coeffs")
  # normal_equations: observed moment matrix times (b1, b2) = cross-moments with y
  expect_equal((m$s11 + m$su2) * r$b1 + m$s12 * r$b2, 1.5 * m$s11 - 0.5 * m$s12)
  expect_equal(m$s12 * r$b1 + m$s22 * r$b2, 1.5 * m$s12 - 0.5 * m$s22)
  expect_equal(r$dstar, (1 + 0.5) * 2 - 0.36)
  expect_equal(r$b2 - (-0.5), 1.5 * 0.5 * 0.6 / r$dstar)
  expect_equal(r$bias_b2_sign, "positive")
  expect_equal(r$slope_single, 1.5 * 1 / 1.5)
  expect_equal(r$reliability, 1 / 1.5)
  # error_free_biased_iff: any of beta1 = 0, su2 = 0, s12 = 0 removes the bias
  expect_equal(morie_attenuation_two_regressor(0, -0.5, 1, 2, 0.6, 0.5)$bias_b2, 0)
  expect_equal(morie_attenuation_two_regressor(1.5, -0.5, 1, 2, 0.6, 0)$bias_b2, 0)
  expect_equal(morie_attenuation_two_regressor(1.5, -0.5, 1, 2, 0, 0.5)$bias_b2, 0)
  # bias_sign: negative beta1 s12 gives a negative bias
  expect_equal(morie_attenuation_two_regressor(-1.5, -0.5, 1, 2, 0.6, 0.5)$bias_b2_sign, "negative")
  expect_error(morie_attenuation_two_regressor(1, 1, 0, 1), "positive variances")
  expect_error(morie_attenuation_two_regressor(1, 1, 1, 1, su2 = -1), "non-negative")
  expect_error(morie_attenuation_two_regressor(1, 1, 1, 1, s12 = 1), "s12\\^2 < s11")
})

test_that("Friedman urn: the mean difference solves the recursion and the share tends to one half", {
  u <- morie_friedman_urn(b0 = 9, r0 = 1, n = 200)
  expect_equal(attr(u, "theorem"), "Research.P4.Friedman.meanDiff_succ")
  expect_equal(u$mean_diff[1], 8)
  T0 <- 10
  for (n in 0:199) expect_equal(u$mean_diff[n + 2], u$mean_diff[n + 1] * (1 - 1 / (T0 + n)))
  expect_lt(abs(u$mean_diff[201]), 8 * 9 / 200)
  expect_lt(abs(u$mean_share[201] - 0.5), 0.01)
  # friedman_step: (B - R)(B + R - 1) is a martingale under the cross-colour rule
  b <- 7; r <- 3
  f <- function(b, r) (b - r) * (b + r - 1)
  expect_equal(b / (b + r) * f(b, r + 1) + r / (b + r) * f(b + 1, r), f(b, r))
  # difference_step
  expect_equal(b / (b + r) * (b - (r + 1)) + r / (b + r) * ((b + 1) - r), (b - r) * (1 - 1 / (b + r)))
  expect_error(morie_friedman_urn(1, 0), "exceed 1")
  expect_error(morie_friedman_urn(2, 2, n = -1), "non-negative")
})

test_that("ruin probability: boundary values, the harmonic equation, optional stopping and the symmetric case", {
  p <- 0.4; N <- 12
  pr <- morie_ruin_probability(p, N)
  expect_equal(attr(pr, "theorem"), "Research.P4.Ruin.ruin_harmonic")
  rho <- 0.6 / 0.4
  expect_equal(attr(pr, "rho"), rho)
  expect_equal(pr[1], 1)
  expect_equal(pr[N + 1], 0)
  for (k in 1:(N - 1)) expect_equal(pr[k + 1], p * pr[k + 2] + (1 - p) * pr[k])
  # optional_stopping_identity: rho^k = p_k + (1 - p_k) rho^N
  for (k in 0:N) expect_equal(rho^k, pr[k + 1] + (1 - pr[k + 1]) * rho^N)
  # deMoivre_step: p rho^(k+2) + q rho^k = rho^(k+1)
  expect_equal(p * rho^5 + (1 - p) * rho^3, rho^4)
  sym <- morie_ruin_probability(0.5, N)
  expect_equal(as.numeric(sym), 1 - (0:N) / N)
  for (k in 1:(N - 1)) expect_equal(sym[k + 1], 0.5 * sym[k + 2] + 0.5 * sym[k])
  expect_equal(as.numeric(morie_ruin_probability(p, N, k = 3)), (rho^3 - rho^N) / (1 - rho^N))
  expect_error(morie_ruin_probability(1, 5), "in \\(0, 1\\)")
  expect_error(morie_ruin_probability(0.3, 5, k = 6), "0..N")
})

test_that("Cox overdispersion: Var N = E N + Var Lambda, equality iff the intensity is constant", {
  r <- morie_cox_overdispersion(w = c(0.7, 0.3), lam = c(1, 5))
  expect_equal(attr(r, "theorem"), "Research.P7.Cox.total_variance")
  m <- 0.7 * 1 + 0.3 * 5
  expect_equal(r$mean, m)
  expect_equal(r$intensity_var, 0.7 * (1 - m)^2 + 0.3 * (5 - m)^2)
  expect_equal(r$variance, r$mean + r$intensity_var)
  expect_gt(r$variance, r$mean)
  expect_equal(r$dispersion, r$variance / r$mean)
  expect_false(r$constant_intensity)
  c0 <- morie_cox_overdispersion(w = c(2, 3), lam = c(4, 4))
  expect_equal(c0$variance, c0$mean)
  expect_true(c0$constant_intensity)
  # a zero-weight component does not break equality
  c1 <- morie_cox_overdispersion(w = c(1, 0), lam = c(2, 9))
  expect_equal(c1$variance, c1$mean)
  expect_true(c1$constant_intensity)
  expect_error(morie_cox_overdispersion(c(1, -1), c(1, 2)), "non-negative weights")
  expect_error(morie_cox_overdispersion(c(1, 1), c(1, -2)), "non-negative")
  v <- morie_zip_vuong_boundary(c(0, 0, 1, 2, 0, 3))
  expect_equal(attr(v, "theorem"), "Research.P7.Cox.llr_zero")
  expect_equal(v$llr, rep(0, 6))
  expect_equal(v$sd, 0)
  expect_true(is.na(v$statistic))
  expect_error(morie_zip_vuong_boundary(c(1.5, 2)), "non-negative integers")
})

