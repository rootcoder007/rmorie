  expect_error(morie_sensitivity_amplification(Lambda = 2), "exactly two")
  expect_error(morie_sensitivity_amplification(Gamma = 2, Lambda = 2), "must exceed")
  expect_error(morie_sensitivity_amplification(Lambda = 0.5, Delta = 2), "at least 1")
})

test_that("design effect: cluster-level inflates by 1 + (M - 1) rho, balanced deflates by 1 - rho, ICC floor", {
  d <- morie_design_effect_direction(rho = 0.1, M = 20)
  expect_equal(attr(d, "theorem"), "Research.P13.Design.quad_form")
  expect_equal(d$deff_cluster_level, 1 + 19 * 0.1)
  expect_equal(d$deff_within_balanced, 0.9)
  expect_equal(d$icc_floor, -1 / 19)
  a <- c(2, -1, 3)
  xc <- matrix(a, nrow = 3, ncol = 4)
  dc <- morie_design_effect_direction(rho = 0.1, M = 4, x = xc)
  expect_equal(dc$ratio, 1 + 3 * 0.1)
  xb <- matrix(c(1, -1, 2, -2, 0.5, -0.5), nrow = 3, byrow = TRUE)
  db <- morie_design_effect_direction(rho = 0.1, M = 2, x = xb)
  expect_equal(db$ratio, 0.9)
  # quad_form: the form as sum x (Omega x)
  x <- matrix(stats::rnorm(12), 3, 4)
  dq <- morie_design_effect_direction(rho = 0.3, M = 4, x = x)
  omega_x <- (1 - 0.3) * x + 0.3 * rowSums(x)
  expect_equal(dq$quad, sum(x * omega_x))
  # quad_indicator at the floor is zero: (1 - rho) M + rho M^2 = 0 at rho = -1/(M - 1)
  ind <- matrix(0, 3, 4); ind[1, ] <- 1
  expect_equal(morie_design_effect_direction(rho = -1 / 3, M = 4, x = ind)$quad, 0)
  expect_error(morie_design_effect_direction(0.1, 1), "at least 2")
  expect_error(morie_design_effect_direction(-0.6, 3), "lie in")
  expect_error(morie_design_effect_direction(0.1, 3, x = matrix(1, 2, 2)), "M. columns")
})

test_that("Basu's elephant: HT mean and variance, and the inclusion probability that breaks any bound", {
  t <- c(1, 2, 3, 100); pi <- c(0.5, 0.5, 0.5, 0.01)
  r <- morie_ht_elephant(t, pi, bound = 1e4)
  expect_equal(attr(r, "theorem"), "Research.P3.Basu.ht_variance")
  expect_equal(r$mean, 106)
  expect_equal(r$terms, t^2 * (1 - pi) / pi)
  expect_equal(r$variance, sum(r$terms))
  # ht_mean/ht_variance from the inclusion indicators: E[t I / pi] = t, Var = (t/pi)^2 pi (1 - pi)
  expect_equal(sum(t / pi * pi), r$mean)
  expect_equal(sum((t / pi)^2 * pi * (1 - pi)), r$variance)
  expect_equal(r$elephant, 4L)
  expect_equal(r$pi_elephant, 100^2 / (2 * (1e4 + 100^2)))
  expect_gt(r$term_elephant, 1e4)
  expect_lt(r$pi_elephant, 1)
  # ratio_bounded: the other terms are below sum t^2 / pi
  expect_lte(sum(r$terms[-4]), sum(t[-4]^2 / pi[-4]))
  expect_error(morie_ht_elephant(t, c(0.5, 0.5, 0.5, 0)), "in \\(0, 1\\]")
  expect_error(morie_ht_elephant(t, pi, bound = 0), "positive")
})

test_that("attractiveness contraction: sup norm within (1 - omega)^n, totals scaled, feedback threshold", {
  S <- matrix(c(0.5, 0.5, 0, 0.5, 0, 0.5, 0, 0.5, 0.5), nrow = 3, byrow = TRUE)
  r <- morie_attractiveness_contraction(S, omega = 0.2, eta = 0.3, B = c(5, 1, 0), n = 6)
  expect_equal(attr(r, "theorem"), "Research.P4.Contraction.decay")
  expect_true(all(r$sup_norm <= r$sup_bound + 1e-12))
  expect_equal(r$sup_bound, 0.8^(0:6) * 5)
  expect_true(r$doubly_stochastic)
  expect_equal(r$total, 0.8^(0:6) * 6)
  expect_equal(r$trajectory[2, ], 0.8 * (0.7 * c(5, 1, 0) + 0.3 * as.numeric(S %*% c(5, 1, 0))))
  expect_equal(r$feedback_threshold, 0.25)
  # feedback_gain: (1 - omega)(1 + eps rho) > 1 iff eps rho > omega / (1 - omega)
  expect_true(0.8 * (1 + 0.3) > 1)
  expect_false(0.8 * (1 + 0.2) > 1)
  S2 <- matrix(c(1, 0, 0.5, 0.5), nrow = 2, byrow = TRUE)
  r2 <- morie_attractiveness_contraction(S2, omega = 0, eta = 1, B = c(1, 3), n = 2)
  expect_false(r2$doubly_stochastic)
  expect_equal(r2$sup_norm[2], 2)
  expect_equal(r2$feedback_threshold, 0)
  expect_equal(morie_attractiveness_contraction(S2, 1, 0.5, c(1, 3), n = 1)$feedback_threshold, Inf)
  expect_error(morie_attractiveness_contraction(S * 2, 0.2, 0.3, c(1, 1, 1)), "unit row sums")
  expect_error(morie_attractiveness_contraction(S, 0.2, 0.3, c(1, 1)), "one value per site")
  expect_error(morie_attractiveness_contraction(S, 1.2, 0.3, c(1, 1, 1)), "lie in")
})

