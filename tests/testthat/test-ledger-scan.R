test_that("the instrumental inequality holds for every IV model and fails on a refuting table", {
  set.seed(3)
  nz <- 3; nx <- 2; ny <- 3; nu <- 4
  pu <- stats::runif(nu); pu <- pu / sum(pu)
  px <- array(stats::runif(nz * nu * nx), c(nz, nu, nx))
  px <- sweep(px, c(1, 2), apply(px, c(1, 2), sum), "/")
  py <- array(stats::runif(nx * nu * ny), c(nx, nu, ny))
  py <- sweep(py, c(1, 2), apply(py, c(1, 2), sum), "/")
  p <- array(0, c(ny, nx, nz))
  for (z in 1:nz) for (x in 1:nx) for (y in 1:ny) p[y, x, z] <- sum(pu * px[z, , x] * py[x, , y])
  r <- morie_instrumental_inequality(p)
  expect_equal(attr(r, "theorem"), "Research.P8.IVInequality.instrumental_inequality")
  expect_true(r$passes)
  expect_lte(r$max, 1)
  expect_equal(unname(r$per_x), colSums(apply(p, c(1, 2), max)))
  bad <- array(0, c(2, 2, 2))
  bad[1, 1, 1] <- 1
  bad[2, 1, 2] <- 1
  b <- morie_instrumental_inequality(bad)
  expect_false(b$passes)
  expect_equal(unname(b$per_x), c(2, 0))
  expect_error(morie_instrumental_inequality(matrix(1, 2, 2)), "\\(y, x, z\\) array")
  expect_error(morie_instrumental_inequality(bad * 2), "sum to one")
})

test_that("binary misclassification attenuates by (se + sp - 1) pi (1 - pi) / (d1 d0); the ordinal map can reverse", {
  r <- morie_misclassified_rd(r1 = 0.3, r0 = 0.1, prevalence = 0.4, sensitivity = 0.8, specificity = 0.9)
  expect_equal(attr(r, "theorem"), "Research.P2.Misclassification.binary_attenuation")
  d1 <- 0.4 * 0.8 + 0.6 * 0.1
  d0 <- 0.4 * 0.2 + 0.6 * 0.9
  expect_equal(r$d1, d1)
  expect_equal(r$d0, d0)
  expect_equal(r$measured_rd, (0.8 + 0.9 - 1) * 0.2 * 0.4 * 0.6 / (d1 * d0))
  expect_equal(r$measured_rd, r$factor * r$true_rd)
  expect_true(r$sign_kept)
  expect_lt(abs(r$measured_rd), abs(r$true_rd))
  # perfect measurement reproduces the true difference
  expect_equal(morie_misclassified_rd(0.3, 0.1, 0.4, 1, 1)$measured_rd, 0.2)
  # se + sp = 1 (uninformative measurement) gives zero
  expect_equal(morie_misclassified_rd(0.3, 0.1, 0.4, 0.5, 0.5)$measured_rd, 0)
  expect_error(morie_misclassified_rd(0.3, 0.1, 1, 0.8, 0.9), "in \\(0, 1\\)")
  expect_error(morie_misclassified_rd(0.3, 0.1, 0.4, 1.2, 0.9), "in \\[0, 1\\]")
  w <- morie_misclassified_contrast(risks = c(0, 0.5, 1), group = c("high", "low", "high"))
  expect_equal(attr(w, "theorem"), "Research.P2.Misclassification.ordinal_witness")
  expect_equal(w$true_contrast, 1)
  expect_equal(w$measured_contrast, 0)
  rv <- morie_misclassified_contrast(risks = c(0, 0.5, 1), group = c("high", "high", "low"))
  expect_equal(rv$measured_contrast, 0.25 - 1)
  expect_true(rv$reversed)
  expect_error(morie_misclassified_contrast(c(0, 1), c("a", "b")), "must both appear")
  expect_error(morie_misclassified_contrast(c(0), c("high")), "at least 2")
})

test_that("amplification: Gamma symmetric, at least one, at most min, monotone, and every Gamma is a curve", {
  g <- morie_sensitivity_amplification(Lambda = c(2, 3, 5), Delta = 4)
  expect_equal(attr(g, "theorem"), "Research.P11.Amplification.level_curve")
  expect_equal(g$Gamma, (c(2, 3, 5) * 4 + 1) / (c(2, 3, 5) + 4))
  expect_equal(g$Gamma, morie_sensitivity_amplification(Lambda = 4, Delta = c(2, 3, 5))$Gamma)
  expect_true(all(g$Gamma >= 1) && all(g$Gamma <= pmin(g$Lambda, g$Delta)))
