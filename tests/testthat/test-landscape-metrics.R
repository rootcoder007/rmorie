test_that("landscape metrics equal landscapemetrics 2.2.1", {
  for (cs in list(list(g = .ls_b, ref = .ls_ref_b, d = 8), list(g = .ls_c, ref = .ls_ref_c, d = 4))) {
    out <- list(p = PatchMetrics(cs$g, 2, cs$d), c = ClassMetrics(cs$g, 2, cs$d), l = LandscapeMetrics(cs$g,
        2, cs$d))
    for (key in names(cs$ref)) {
      lv <- substr(key, 1, 1)
      mt <- substring(key, 3)
      expect_equal(out[[lv]][[mt]], cs$ref[[key]], tolerance = 1e-12, info = key)
    }
  }
})

test_that("patch labels, FRAGSTATS clumpy sign, AI and diversity", {
  lab <- LabelPatches(rbind(c(1, 1, 2), c(2, 1, 2)), directions = 4)
  expect_equal(lab$labels, rbind(c(1L, 1L, 3L), c(2L, 1L, 3L)))
  g <- rbind(c(1, 1, 2, 2), c(1, 3, 2, 2), c(1, 1, 3, 2), c(3, 1, 2, 2))
  expect_equal(ClassMetrics(g, directions = 4)$clumpy[3], -1)
  expect_equal(ClassMetrics(rbind(c(1, 1, 1, 2), c(1, 1, 1, 2), c(1, 1, 1, 2)), directions = 4)$ai[1], 100)
  L <- LandscapeMetrics(g, directions = 4)
  p <- ClassMetrics(g, directions = 4)$pland / 100
  expect_equal(L$shdi, -sum(p * log(p)))
  expect_equal(L$dominance, log(3) - L$shdi)
  expect_error(LabelPatches(matrix(1), directions = 6), "directions")
})
