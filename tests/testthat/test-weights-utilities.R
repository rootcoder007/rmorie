test_that("WeightsSummary equals spweights.constants, card and eigenw", {
  s <- WeightsSummary(WeightsStyle(.sw_W, "W"))
  expect_equal(c(s$S0, s$S1, s$S2), c(5, 5.5080559772118214, 21.097882817038659), tolerance = 1e-13)
  expect_equal(s$eigenvalues, c(-0.99999999999999822, -0.47843087682141028, -1.5003759331839197e-16, 0,
      0.47843087682141078, 0.99999999999999822), tolerance = 1e-12)
  b <- WeightsSummary(.sw_W)
  expect_equal(unname(b$cardinality), c(2, 2, 2, 3, 1, 0))
  expect_equal(unname(b$islands), 6L)
  expect_true(b$symmetric)
  expect_false(WeightsSummary(rbind(c(0, 1), c(0, 0)))$symmetric)
})

test_that("SinkhornWeights is doubly stochastic", {
  # units 1-4 form a 4-cycle, so the block has total support
  M <- SinkhornWeights(.sw_W[1:4, 1:4])$W
  expect_lt(max(abs(rowSums(M) - 1)), 1e-12)
  expect_lt(max(abs(colSums(M) - 1)), 1e-12)
  expect_error(WeightsStyle(.sw_W, "X"), "style")
})
