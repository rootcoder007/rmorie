test_that("embedding quality, alienation and dissimilarity checks by hand", {
  line <- as.matrix(dist(0:5))
  e <- EmbeddingQuality(line, line, 2)
  expect_equal(unlist(e), c(trustworthiness = 1, continuity = 1, qnx = 1, lcmc = 1 - 2 / 5))
  expect_lt(EmbeddingQuality(line, as.matrix(dist(c(0, 2, 1, 3, 4, 5))), 1)$trustworthiness, 1)
  a <- c(1, 2, 3)
  b <- c(1.1, 1.9, 3.2)
  expect_equal(AlienationCoefficient(a, b), sqrt(1 - (sum(a * b) / sqrt(sum(a^2) * sum(b^2)))^2))
  cc <- DissimilarityCheck(rbind(c(0, 1, 5), c(1, 0, 1), c(5, 1, 0)))
  expect_equal(c(cc$triangle_violations, cc$max_violation), c(1, 3))
  expect_false(cc$euclidean)
  expect_error(SmacofMds(.md_D, type = "mspline"), "type")
})

