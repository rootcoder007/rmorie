# R/ucfR_native.R, R/tlsate_native.R, R/tlstoch_native.R: the GroupLens prediction, the
# sample-effect TMLE and the stochastic-shift TMLE, each recomputed from the equations in the
# file headers.

.ts <- function(name) get(name, envir = environment(morie_tlsate))

test_that("GroupLens correlates over co-rated items only and predicts from deviations", {
  co <- .ts(".ucfR_co_rated")(c(a = 5, b = 3, c = 4), c(b = 2, c = 5, d = 1))
  expect_equal(co$items, c("b", "c"))
  expect_equal(co$n, 2L)
  expect_equal(co$a, c(3, 4))
  expect_equal(co$b, c(2, 5))
  sw <- .ts(".ucfR_significance_weight")
  expect_equal(sw(10, 50), 0.2)
  expect_equal(sw(80, 50), 1)
  expect_error(sw(10, 0), "threshold must be positive")
  pe <- .ts(".ucfR_pearson")
  ra <- c(i1 = 5, i2 = 3, i3 = 4, i4 = 1)
  rb <- c(i1 = 4, i2 = 2, i3 = 5, i4 = 2, i5 = 3)
  p <- pe(ra, rb)
  expect_equal(p$w, stats::cor(ra, rb[names(ra)]))
  expect_equal(p$n_common, 4L)
  expect_false(p$degenerate)
  expect_false(p$significance_applied)
  ps <- pe(ra, rb, significance = TRUE, threshold = 8)
  expect_equal(ps$w, stats::cor(ra, rb[names(ra)]) * 0.5)
  expect_true(ps$significance_applied)
  expect_error(pe(ra, c(i1 = 1), min_common = 2), "only 1 co-rated items, below the minimum of 2")
  flat <- pe(ra, c(i1 = 3, i2 = 3, i3 = 3, i4 = 3))
  expect_true(flat$degenerate)
  expect_equal(flat$w, 0)
  nb <- .ts(".ucfR_neighbours")
  others <- list(u1 = rb, u2 = c(i1 = 1, i2 = 5, i3 = 2, i4 = 5), u3 = c(i1 = 2, i2 = 2, i3 = 2, i4 = 2),
                 u4 = c(i9 = 1))
  n <- nb(ra, others)
  # u3 is degenerate and u4 shares nothing; the rest are ranked by |w|, the disagreer included
  expect_equal(vapply(n$neighbours, `[[`, "", "user"), c("u2", "u1"))
  expect_equal(n$neighbours[[1]]$w, stats::cor(ra, others$u2[names(ra)]))
  expect_equal(n$n, 2L)
  expect_equal(nb(ra, others, top_k = 1)$n, 1L)
  expect_equal(nb(ra, list())$n, 0L)
  pr <- .ts(".ucfR_predict_rating")
  r <- pr(ra, others, "i5")
  # only u1 rated i5: the target's mean plus u1's deviation on i5 (the weight cancels)
  expect_equal(r$user_mean, mean(ra))
  expect_equal(r$estimate, mean(ra) + sign(p$w) * (3 - mean(rb)))
  expect_equal(r$naive_weighted_mean, 3)
  expect_equal(r$n_neighbours, 1L)
  expect_false(r$fell_back)
  others$u2 <- c(others$u2, i5 = 4)
  r2 <- pr(ra, others, "i5")
  w1 <- stats::cor(ra, rb[names(ra)])
  w2 <- stats::cor(ra, others$u2[names(ra)])
  expect_equal(r2$estimate, mean(ra) + (w1 * (3 - mean(rb)) + w2 * (4 - mean(others$u2))) / (abs(w1) + abs(w2)))
  expect_equal(r2$n_neighbours, 2L)
  fb <- pr(ra, others, "i7")
  expect_true(fb$fell_back)
  expect_equal(fb$estimate, mean(ra))
  expect_equal(fb$n_neighbours, 0L)
  expect_error(pr(numeric(), others, "i5"), "rated nothing")
  expect_match(.ts(".ucfR_cheatsheet")(), "^ucfR: people who agreed before")
  # the registry entry is that function: compared by what it returns (coverage rewrites the
  # namespace copy's body and leaves the list's copy as it was loaded)
  expect_identical(formals(morie_ucfR$user_based_cf), formals(.ts(".ucfR_predict_rating")))
  expect_equal(morie_ucfR$user_based_cf(ra, others, "i5"), r2)
})

test_that("the sample-effect TMLE keeps the point estimate and narrows the interval by the conditional-effect variance", {
  set.seed(4)
  n <- 300
  w <- stats::rnorm(n)
  g <- stats::plogis(0.4 * w)
  a <- stats::rbinom(n, 1, g)
  q1 <- stats::plogis(0.5 + 0.8 * w)
  q0 <- stats::plogis(-0.3 + 0.2 * w)
  y <- stats::rbinom(n, 1, ifelse(a == 1, q1, q0))
  chk <- .ts(".tlsate_check")
  expect_error(chk(a, y[-1], q1, q0, g), "differ in length")
  expect_error(chk(a, y, q1, q0, replace(g, 1, 1)), "strictly inside")
  expect_equal(chk(a, y, q1, q0, g)$n, n)
  expect_equal(.ts(".tlsate_logit")(c(0.5, 0, 1)), c(0, log(1e-9 / (1 - 1e-9)), -log(1e-9 / (1 - 1e-9))))
  expect_equal(.ts(".tlsate_expit")(c(0, -800)), c(0.5, 0))
  v <- stats::rnorm(20)
  expect_equal(.ts(".tlsate_var")(v), stats::var(v))
  expect_equal(.ts(".tlsate_se")(v), stats::sd(v) / sqrt(20))
  psi0 <- mean(q1 - q0)
  h <- a / g - (1 - a) / (1 - g)
  qa <- ifelse(a == 1, q1, q0)
  expect_equal(.ts(".tlsate_pate_influence_curve")(a, y, q1, q0, g, psi0), h * (y - qa) + q1 - q0 - psi0)
  expect_equal(.ts(".tlsate_sate_influence_curve")(a, y, q1, q0, g), h * (y - qa))
  gap <- .ts(".tlsate_variance_gap")(a, y, q1, q0, g, psi0)
  expect_equal(gap$gap, gap$var_pate - gap$var_sate)
  expect_equal(gap$var_conditional_effect, stats::var(q1 - q0))
  fit <- .ts(".tlsate_sate_tmle")(a, y, q1, q0, g)
  # the fluctuation solves the score equation: the sample influence curve has mean zero
  e <- fit$psi
  q1s <- stats::plogis(stats::qlogis(q1) + 0)
  ic_s <- .ts(".tlsate_sate_influence_curve")
  # recompute the fluctuation by the same Newton steps
  off <- stats::qlogis(qa)
  eps <- 0
  for (it in 1:60) {
    p <- stats::plogis(off + eps * h)
    he <- sum(h^2 * p * (1 - p))
    if (he < 1e-12) break
    eps <- eps + sum(h * (y - p)) / he
  }
  q1s <- stats::plogis(stats::qlogis(q1) + eps / g)
  q0s <- stats::plogis(stats::qlogis(q0) - eps / (1 - g))
  expect_equal(fit$psi, mean(q1s - q0s), tolerance = 1e-10)
  expect_equal(mean(ic_s(a, y, q1s, q0s, g)), 0, tolerance = 1e-8)
  icp <- h * (y - ifelse(a == 1, q1s, q0s)) + q1s - q0s - fit$psi
  expect_equal(fit$se_population, stats::sd(icp) / sqrt(n), tolerance = 1e-10)
  expect_equal(fit$se_sample, stats::sd(ic_s(a, y, q1s, q0s, g)) / sqrt(n), tolerance = 1e-10)
  expect_lt(fit$se_sample, fit$se_population)
  expect_equal(fit$width_ratio, fit$se_sample / fit$se_population)
  expect_equal(fit$ci_sample, fit$psi + c(-1.96, 1.96) * fit$se_sample)
  expect_equal(fit$ci_population, e + c(-1.96, 1.96) * fit$se_population)
  expect_identical(morie_tlsate, .ts(".tlsate_sate_tmle"))
  pv <- .ts(".tlsate_paired_variance")
  ic <- c(1, 3, -2, 4, 0.5, 1.5)
  pp <- pv(c("p1", "p1", "p2", "p2", "p3", "p3"), ic)
  sums <- c(2, 1, 1)
  expect_equal(pp$se, sqrt(stats::var(sums) / 3))
  expect_equal(pp$n_pairs, 3L)
  expect_error(pv(c("p1", "p1"), ic), "6 influence values")
  expect_error(pv(c("p1", "p1", "p1", "p2", "p2", "p2"), ic), "exactly 2 units")
  expect_match(.ts(".tlsate_cheatsheet")(), "^tlsate: in a cluster randomized trial")
})

test_that("the stochastic-shift TMLE uses a density ratio as its clever covariate and reports the shifted mean", {
  vec <- .ts(".tlstoch_vec")
  mat <- .ts(".tlstoch_mat")
  expect_equal(vec(NULL), numeric(0))
  expect_equal(vec(1:3), c(1, 2, 3))
  expect_equal(dim(mat(NULL)), c(0L, 0L))
  expect_equal(mat(1:3), matrix(c(1, 2, 3), ncol = 1))
  m <- mat(matrix(1:4, 2))
  expect_equal(storage.mode(m), "double")
  expect_equal(mat(list(1:2, 3)), matrix(c(1, 3, 2, 0), 2))
  expect_equal(dim(mat(list())), c(0L, 0L))
  sr <- .ts(".tlstoch_shift_regime")
  s <- sr(c(1, 2, 3), 0.5, lower = 1.6, upper = 3.2)
  expect_equal(s$shifted, c(1.6, 2.5, 3.2))
  expect_equal(s$n_clipped, 2L)
  expect_equal(s$fraction_clipped, 2 / 3)
  expect_equal(sr(c(1, 2, 3), -1)$shifted, c(0, 1, 2))
  ps <- .ts(".tlstoch_positivity_shift")
  a <- c(1, 2, 3, 4, 5, 6)
  p0 <- ps(a, 1)
  expect_equal(p0$fraction_outside, 1 / 6)
  expect_equal(p0$support, c(1, 6))
  expect_false(p0$satisfied)
  expect_true(ps(a, 0)$satisfied)
  w <- c(0, 0, 0, 1, 1, 1)
  pw <- ps(a, 1, W = w, bins = 2)
  # within each covariate bin the top exposure shifts out of its support: two of six
  expect_equal(pw$fraction_outside, 2 / 6)
  expect_equal(pw$bins, 2L)
  expect_false(pw$satisfied)
  expect_true(ps(a, 1, W = rep(0, 6), bins = 3)$fraction_outside == 1 / 6)
  qfn <- function(a, w) 1 + 2 * a + w[1]
  W <- cbind(c(0.5, -0.5, 1), 0)
  se <- .ts(".tlstoch_stochastic_estimand")(qfn, c(1, 2, 3), W, 0.5)
  expect_equal(se$psi, mean(1 + 2 * (c(1, 2, 3) + 0.5) + W[, 1]))
  expect_equal(se$observed_mean, mean(1 + 2 * c(1, 2, 3) + W[, 1]))
  expect_equal(se$contrast, 1)
  expect_error(.ts(".tlstoch_stochastic_estimand")(qfn, 1:2, W, 0.5), "2 exposures but 3 covariate rows")
  dr <- .ts(".tlstoch_density_ratio")
  gfn <- function(a, w) stats::dnorm(a, mean = w[1], sd = 1)
  r <- dr(c(1, 2, 3), W, 0.5, gfn)
  expect_equal(r$H, stats::dnorm(c(1, 2, 3) - 0.5, W[, 1]) / stats::dnorm(c(1, 2, 3), W[, 1]))
  expect_equal(r$max, max(r$H))
  expect_error(dr(c(1, 2, 3), W, 0.5, function(a, w) 0), "zero density at observation 1")
  # with a constant density ratio the fluctuation is the mean residual and the estimate the shifted mean
  set.seed(2)
  n <- 50
  av <- stats::runif(n, 0, 4)
  Wm <- cbind(stats::rnorm(n))
  yv <- 1 + 2 * av + Wm[, 1] + stats::rnorm(n, sd = 0.1)
  fit <- .ts(".tlstoch_shift_tmle")(yv, av, Wm, qfn, function(a, w) 1, 0.5)
  eps <- mean(yv - (1 + 2 * av + Wm[, 1]))
  expect_equal(fit$epsilon, eps, tolerance = 1e-10)
  expect_equal(fit$psi, mean(1 + 2 * (av + 0.5) + Wm[, 1]) + eps, tolerance = 1e-10)
  expect_equal(fit$max_density_ratio, 1)
  expect_equal(fit$mean_eic, 0, tolerance = 1e-10)
  dv <- (yv - (1 + 2 * av + Wm[, 1] + eps)) + (1 + 2 * (av + 0.5) + Wm[, 1] + eps) - fit$psi
  expect_equal(fit$se, sqrt(sum((dv - mean(dv))^2)) / n, tolerance = 1e-10)
  expect_equal(fit$ci, fit$psi + c(-1.96, 1.96) * fit$se)
  # a degenerate clever covariate stops the fluctuation at zero
  fit0 <- .ts(".tlstoch_shift_tmle")(yv, av, Wm, qfn, function(a, w) if (a < 0) 1e-9 else 1, 100, iters = 5)
  expect_equal(fit0$epsilon, 0)
  expect_match(.ts(".tlstoch_cheatsheet")(), "^tlstoch: static and dynamic regimes")
  # the registry entry is that function: compared by what it returns, since coverage rewrites the
  # namespace copy's body and leaves the list's copy as it was loaded
  expect_identical(formals(morie_tlstoch$stochasticregime), formals(.ts(".tlstoch_shift_tmle")))
  reg <- morie_tlstoch$stochasticregime(yv, av, Wm, qfn, function(a, w) if (a < 0) 1e-9 else 1, 100, iters = 5)
  expect_equal(reg, fit0)
})
