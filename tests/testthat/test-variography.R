test_that("FitVariogram reaches the gstat fit.variogram optimum", {
  f40 <- .vg_field40()
  sv <- SampleVariogram(f40$z, f40$P)
  ref <- list(
    "1" = c(0.36583408124640204, 0.66634407798827544, 5.2978571490734554, 17.155097590681635),
    "6" = c(0.43151393240078056, 0.6407098504105383, 6.1565123376801552, 0.7322266890843403),
    "7" = c(0.43981722167784892, 1.3041288051335065, 14.007268533820726, 3.4065717992905231)
  )
  for (m in names(ref)) {
    f <- FitVariogram(sv, list(list(model = "Nug", psill = 0.1), list(model = "Sph", psill = 1, range = 3)),
        method = as.integer(m))
    expect_lte(f$sse, ref[[m]][4] * (1 + 1e-9))
    expect_equal(f$sse, ref[[m]][4], tolerance = 1e-9)
    expect_equal(c(f$model[[1]]$psill, f$model[[2]]$psill, f$model[[2]]$range), ref[[m]][1:3],
        tolerance = 1e-3)
  }
})

