test_that("VariogramMap is point-symmetric and VgmSpectralDensity integrates to C(0)", {
  r <- VariogramMap(c(1, 2, 4), rbind(c(0, 0), c(1, 0), c(0, 1)), cutoff = 1, width = 1)
  expect_equal(r$gamma[r$dx == 1 & r$dy == 0], 0.5)
  expect_equal(r$gamma[r$dx == -1 & r$dy == 1], 2)
  m <- list(model = "Gau", psill = 1, range = 1.3)
  w <- (seq_len(200000) - 0.5) * 0.002
  expect_equal(2 * 0.002 * sum(VgmSpectralDensity(w, m, d = 1)), 1, tolerance = 1e-6)
  expect_error(VgmCovariance(1, list(model = "Pow", range = 1)), "unbounded")
})
