test_that("routing heuristics produce feasible covering routes", {
  u <- .morie_random_uniform(200, seed = 41)
  P <- rbind(c(50, 50), cbind(100 * u[2:11], 100 * u[22:31]))
  D <- as.matrix(dist(P))
  q <- c(0, 1 + floor(4 * u[42:51]))
  r <- SavingsRoutes(D, 1:10, q, 10)
  expect_equal(sort(unlist(r$routes)), 1:10)
  expect_true(all(vapply(r$routes, function(x) sum(q[x + 1]), 0) <= 10))
  ready <- c(0, 80 * u[62:71])
  due <- c(1000, ready[-1] + 70)
  s <- c(0, rep(4, 10))
  tw <- VrptwInsertion(D, q, 12, ready, due, s)
  expect_equal(sort(unlist(tw$routes)), 1:10)
  md <- MultiDepotVrp(D, c(0, 1), q, 9)
  expect_true(all(D[1, md$assignment[["0"]] + 1] <= D[2, md$assignment[["0"]] + 1]))
  pd <- PickupDeliveryRoutes(D, list(c(2, 3), c(4, 5)), c(2, 3), 4)
  for (x in pd$routes) expect_true(match(2, x, 0) <= match(3, x, 0))
  expect_equal(TripGeneration(rbind(c(1, 2), c(3, 4)), c(0.5, 2)), c(4.5, 9.5))
})
