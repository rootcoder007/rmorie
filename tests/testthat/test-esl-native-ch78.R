test_that("criteria follow their formulas", {
  expect_equal(morie_esl_aic_score(-16.170902885115233, 3)$estimate, 38.341805770230465, tolerance = 1e-14)
  expect_equal(morie_esl_bic_score(-16.170902885115233, 3, 40)$estimate, 43.40844413257227, tolerance = 1e-14)
  expect_equal(bic_posterior_probs(c(40.1, 41.3, 45))$probs[1], 0.6115814359726194, tolerance = 1e-14)
  ce <- morie_esl_cross_entropy(diag(3), rbind(c(0.7, 0.2, 0.1), c(0.1, 0.8, 0.1), c(0.2, 0.3, 0.5)))
  expect_equal(ce$estimate, mean(-log(c(0.7, 0.8, 0.5))), tolerance = 1e-14)
  expect_equal(morie_esl_one_se_rule(c(0.30, 0.25, 0.22, 0.23, 0.26), c(0.02, 0.02, 0.03, 0.02, 0.02))$estimate, 2)
  v <- morie_esl_vc_bound(0.1, 5, 100)
  expect_equal(c(v$epsilon, v$bound), c(1.1130569562097425, 1.3053964481594105), tolerance = 1e-14)
  r <- morie_esl_vc_bound(0.2, 5, 100, task = "regression")
  expect_equal(r$bound, 0.39491778481159401, tolerance = 1e-14)
  expect_equal(morie_esl_vc_bound(0.2, 90, 100, task = "regression")$bound, Inf)
  expect_equal(r$practical_bound, 0.37880951126675527, tolerance = 1e-14)
})

test_that("GCV equals smooth.spline and the prediction-error terms their formulas", {
  x <- sort(((7 * (1:50)) %% 47) / 47 * 3)
  y <- sin(2 * x) + 0.3 * cos(9 * (1:50))
  f <- smooth.spline(x, y, spar = 0.6)
  expect_equal(morie_esl_gcv(y, fitted(f), f$df)$gcv, f$cv.crit, tolerance = 1e-12)
  X <- cbind(1, sin(1:20), log(1:20))
  pe <- morie_esl_linear_prediction_error(X, c(1, 0.3, 2), 0.5)
  expect_equal(c(pe$h_norm2, pe$err_x0), c(0.056426555710195003, 0.528213277855097529), tolerance = 1e-12)
  expect_equal(mean(apply(X, 1, function(r) morie_esl_linear_prediction_error(X, r, 0.5)$variance)), 3 * 0.5 / 20,
               tolerance = 1e-12)
})

test_that("basis fit se equals predict.lm, the Bayesian posterior its formula, bootstrap agrees", {
  x <- sort(((7 * (1:50)) %% 47) / 47 * 3)
  y <- sin(2 * x) + 0.3 * cos(9 * (1:50))
  tp <- function(v) cbind(1, v, v^2, pmax(v - 1, 0)^3, pmax(v - 2, 0)^3)
  H <- tp(x)
  Hn <- tp(c(0.5, 2.2))
  pr <- predict(lm(y ~ H - 1), list(H = Hn), se.fit = TRUE)
  s <- morie_esl_basis_fit_se(H, y, Hn, divisor = "N-p")
  expect_equal(c(s$fit, s$se), unname(c(pr$fit, pr$se.fit)), tolerance = 1e-12)
  s0 <- morie_esl_basis_fit_se(H, y, Hn)
  expect_equal(s0$se, s$se * sqrt(45 / 50), tolerance = 1e-12)
  b <- morie_esl_bayes_basis_posterior(H, y, 0.09, 2, Hnew = Hn)
  expect_equal(b$mean[1:3], c(-0.012817755105172329, 2.558936604922364744, -1.691688010698427114), tolerance = 1e-12)
  expect_equal(b$mu_sd, c(0.070516476962409258, 0.081728670405200821), tolerance = 1e-12)
  bt <- morie_esl_parametric_bootstrap(H, y, Hn, B = 4000, seed = 3)
  expect_lt(max(abs(bt$boot_se / s0$se - 1)), 0.06)
  d <- morie_esl_dirichlet_posterior(c(12, 5, 3))
  expect_equal(d$mean, c(12, 5, 3) / 20)
  expect_equal(d$var, (c(12, 5, 3) / 20) * (1 - c(12, 5, 3) / 20) / 21, tolerance = 1e-14)
})
