test_that("search theory formulas", {
  expect_equal(round(LateralRange(c(0.5, 1, 2), 1), 6), c(0.272623, 0.076494, 0.019698))
  expect_equal(round(SearchPod(1, "inverse_cube"), 4), 0.7899)
  expect_equal(ParallelSweepPod(1, 1.3), 2 * pnorm(sqrt(pi) / 2.6 * sqrt(2)) - 1, tolerance = 1e-12)
  s <- SearchSuccess(c(0.5, 0.3, 0.2), c(0.8, 0.5, 0))
  expect_equal(s$pos, 0.55)
  expect_equal(s$poc_updated, c(0.1, 0.15, 0.2) / 0.45)
  m <- DatumProbabilityMap(c(-1, 0, 1), c(-1, 0, 1))
  expect_equal(round(c(m$poc[1, 1], m$outside), 6), c(0.116516, 0.533935))
  expect_equal(round(OptimalCircularSearch(1, 1, pi / 4)$pos, 6), 0.090204)
  a <- OptimalEffortAllocation(c(0.5, 0.5), c(1, 1), 1, 2)
  expect_equal(a$effort, c(1, 1), tolerance = 1e-10)
  expect_error(LateralRange(1, 1, "bogus"), "model must be")
})
