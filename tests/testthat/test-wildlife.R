test_that("home range, distance sampling and survey models", {
  expect_equal(McpHomeRange(rbind(c(0, 0), c(4, 0), c(4, 3), c(0, 3), c(2, 1)), 100)$area, 12)
  x <- c(0.1, 0.4, 0.2, 0.8, 0.5, 0.05, 0.3, 1.1, 0.6, 0.25)
  r <- DistanceSampling(x, width = 1e6, effort = 2)
  expect_equal(r$sigma, sqrt(mean(x^2)), tolerance = 1e-8)
  expect_equal(r$density, 10 / (4 * r$esw), tolerance = 1e-12)
  y <- rbind(c(1, 0, 1), c(0, 0, 0), c(1, 1, 0), c(0, 0, 0), c(0, 1, 0), c(0, 0, 0))
  o <- OccupancyModel(y)
  expect_equal(o$naive_occupancy, 0.5)
  expect_equal(o$conditional_occupancy[1], 1)
  expect_equal(NmixtureModel(rbind(c(3, 2, 4), c(0, 1, 0)), K = 50)$K, 50)
})

test_that("connectivity, suitability, Mantel, gene flow, Hanski", {
  expect_equal(CircuitResistance(matrix(1, 2, 2), rbind(c(1, 1), c(1, 2)))$resistance[1, 2], 1 / (1 + 1 / 3))
  lc <- LeastCostPath(rbind(c(1, 1, 1), c(9, 9, 1), c(1, 1, 1)), c(1, 1), c(3, 1), 4)
  expect_equal(lc$cost, 6)
  expect_equal(ResistanceFromSuitability(c(0, 1), 4), c(100, 1))
  expect_equal(HabitatSuitabilityIndex(list(c(0.5, 1), c(0.8, 1)))[1], sqrt(0.4))
  A <- rbind(c(0, 1, 2, 3), c(1, 0, 1, 2), c(2, 1, 0, 1), c(3, 2, 1, 0))
  C <- rbind(c(0, 2, 1, 5), c(2, 0, 3, 1), c(1, 3, 0, 2), c(5, 1, 2, 0))
  expect_equal(PartialMantel(A, A, C, nsim = 0)$statistic, 1)
  expect_equal(GeneFlowNm(0.2), 1)
  expect_equal(HanskiConnectivity(rbind(c(0, 0), c(1, 0)), c(1, 1), c(4, 9)), c(3, 2) * exp(-1))
})
