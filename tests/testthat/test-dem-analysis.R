  expect_equal(.dm_flat(Watershed(fd, c(6, 4))), .dm_ref$ws)
})

test_that("fill, stream order, D-infinity, MFD, curvature and viewshed by hand", {
  dem <- rbind(c(5, 5, 5, 5), c(5, 1, 2, 5), c(5, 3, 4, 3), c(5, 5, 5, 5))
  f <- FillSinks(dem)
  expect_equal(f[2:3, 2:3], rbind(c(3, 3), c(3, 4)))
  expect_equal(FillSinks(f), f)
  fd <- rbind(c(2, 0, 8), c(0, 4, 0), c(0, 4, 0))
  acc <- FlowAccumulation(fd)
  expect_equal(StreamOrder(fd, acc, 1)[3, 2], 2)
  expect_equal(StreamOrder(fd, acc, 1, "shreve")[3, 2], 2)
  expect_equal(DinfFlowDirection(rbind(c(2, 1, 0), c(3, 2, 1), c(4, 3, 2)))[2, 2], pi / 4)
  expect_equal(MfdFlowAccumulation(rbind(c(2, 1), c(1, 0)))[2, ], c(1 + 1 / (2 + sqrt(2)^1.1), 4))
  bowl <- outer(0:2, 0:2, function(y, x) (x - 1)^2 + (y - 1)^2)
  expect_equal(Curvature(bowl)$total[2, 2], -4)
  expect_equal(TopographicWetnessIndex(matrix(12), matrix(0.3), res = 5)[1, 1], log(60 / tan(0.3)))
  v <- Viewshed(rbind(c(0, 0, 0, 0, 0), c(0, 0, 5, 0, 0), c(0, 0, 0, 0, 0)), c(2, 1), observer_height = 1)
  expect_equal(v[2, 3:5], c(1, 0, 0))
  expect_error(TerrainIndices(.dm_dem, neighbors = 6), "neighbors")
})
