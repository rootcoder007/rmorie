test_that("numerical and discrete algorithms satisfy their definitions", {
  f <- PollardRho(600851475143)
  expect_equal(prod(f), 600851475143)
  expect_equal(f, c(71, 839, 1471, 6857))
  expect_equal(LegendrePolynomials(1, 5), matrix(1, 1, 6))
  expect_true(ResolutionRefutation(list(1, c(-1, 2), -2))$unsatisfiable)
  expect_false(ResolutionRefutation(list(c(1, 2), c(-1, 2), 3))$unsatisfiable)
  z <- .morie_random_normal(32, seed = 7)
  pt <- PolarTransform(z)
  expect_equal(pt$radius, sqrt(sum(z^2)), tolerance = 1e-14)
  expect_equal(PolarTransform(list(pt$radius, pt$angles), inverse = TRUE), z, tolerance = 1e-12)
  expect_equal(PanterDiteBound(5, 4)$mse, sqrt(3) * pi / 2 * 4 / 1024, tolerance = 1e-15)
  expect_equal(LogitProportion(6, 24)$vi, 1 / 6 + 1 / 18, tolerance = 1e-14)
})
