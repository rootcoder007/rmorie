.ks_energy <- function(n, h, c, o) {
  d <- function(a, b) sqrt(sum((a - b)^2))
  max(27.888 * (1 / d(o, n) + 1 / d(c, h) - 1 / d(o, h) - 1 / d(c, n)), -9.9)
}

.nerf <- function(a, b, c, bond, angle, torsion) {
  bc <- (c - b) / sqrt(sum((c - b)^2))
  ab <- b - a
  n <- c(ab[2] * bc[3] - ab[3] * bc[2], ab[3] * bc[1] - ab[1] * bc[3], ab[1] * bc[2] - ab[2] * bc[1])
  n <- n / sqrt(sum(n^2))
  m <- c(n[2] * bc[3] - n[3] * bc[2], n[3] * bc[1] - n[1] * bc[3], n[1] * bc[2] - n[2] * bc[1])
  ang <- angle * pi / 180
  tor <- torsion * pi / 180
  c + (-bond * cos(ang)) * bc + bond * sin(ang) * cos(tor) * m + bond * sin(ang) * sin(tor) * n
}

.helix <- function(nres, phi = -57, psi = -47) {
  N <- list(c(0, 0, 0))
  CA <- list(c(1.458, 0, 0))
  t <- 111.2 * pi / 180
  C <- list(c(1.458 - 1.525 * cos(t), 1.525 * sin(t), 0))
  for (i in seq_len(nres - 1)) {
    N[[i + 1]] <- .nerf(N[[i]], CA[[i]], C[[i]], 1.329, 116.2, psi)
    CA[[i + 1]] <- .nerf(CA[[i]], C[[i]], N[[i + 1]], 1.458, 121.7, 180)
    C[[i + 1]] <- .nerf(C[[i]], N[[i + 1]], CA[[i + 1]], 1.525, 111.2, phi)
  }
  lapply(seq_len(nres), function(i) list(N[[i]], CA[[i]], C[[i]], .nerf(N[[i]], CA[[i]], C[[i]], 1.231, 120.5, psi + 180)))
}

test_that("the hydrogen-bond energy is the Kabsch-Sander formula", {
  n <- c(0.3, -0.2, 0.1)
  h <- c(1.2, 0.1, -0.1)
  cc <- c(4, 0.5, 0.2)
  o <- c(2.9, 0.3, 0)
  expect_equal(DsspHbondEnergy(n, h, cc, o), .ks_energy(n, h, cc, o), tolerance = 1e-12)
  expect_equal(DsspHbondEnergy(c(0, 0, 0), c(1, 0, 0), c(1.9, 0, 0), c(1.2, 0, 0)), -9.9)
})

test_that("reported hydrogen bonds recompute from the coordinates", {
  res <- .ubq_res()
  r <- DsspAssign(res, sequence = .ubq_seq)
  expect_equal(nchar(r$ss), 30)
  for (i in seq_along(res)) {
    h <- if (i == 1) res[[1]][1, ] else {
      u <- res[[i - 1]][3, ] - res[[i - 1]][4, ]
      res[[i]][1, ] + u / sqrt(sum(u^2))
    }
    hb <- r$hbonds[[i]]
    for (k in seq_along(hb$acceptor)) {
      a <- hb$acceptor[k]
      expect_lt(hb$energy[k], -0.5)
      expect_equal(hb$energy[k], .ks_energy(res[[i]][1, ], h, res[[a]][3, ], res[[a]][4, ]), tolerance = 1e-12)
    }
  }
  expect_length(r$hbonds[[regexpr("P", .ubq_seq)]]$acceptor, 0)
})

test_that("the assignment follows the DSSP definitions", {
  r <- DsspAssign(.ubq_res(), sequence = .ubq_seq)
  bond <- function(d, a) a %in% r$hbonds[[d]]$acceptor
  ss <- strsplit(r$ss, "")[[1]]
  turn4 <- vapply(1:30, function(i) i + 4 <= 30 && bond(i + 4, i), logical(1))
  for (i in which(ss == "H")) expect_true(any(vapply(max(2, i - 3):i, function(k) turn4[k] && turn4[k - 1], logical(1))))
  lad <- c()
  for (br in r$bridges) lad <- c(lad, br$i[1]:br$i[length(br$i)], br$j[1]:br$j[length(br$j)])
  expect_true(all(which(ss %in% c("E", "B")) %in% lad))
  expect_gte(sum(ss == "E"), 8)
})

test_that("an ideal alpha helix is H inside", {
  res <- .helix(16)
  r <- DsspAssign(res)
  expect_equal(r$ss, paste0("-", strrep("H", 14), "-"))
  expect_equal(DsspAssign(res, prefer_pi = FALSE)$ss, r$ss)
})
